#!/usr/bin/env python3
"""Prepare one Brown/Oscar environment without submitting jobs or loading weights.

All writable preparation paths are beneath --base-dir; the Git checkout remains
editable and unchanged. Run each phase separately. Shell/module commands are
accepted only through an explicit, reviewed --site-env script.
"""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path, PurePosixPath
import re
import shlex
import shutil
import subprocess
import sys
import tarfile
import tempfile
from urllib.parse import urlsplit

CODE_REVISION = '6c14bed1d62fbecb559d5902459c6093c38da405'
CHECKPOINT_REVISION = '92aa28bc678f523f8641fdb2f9e5159f614d1c02'
CODE_URL = 'https://github.com/Tier-Flow/LoopVL.git'
MODEL_REPO = 'TierFlow/LoopVL'
STAGES = ('smoke', 'pilot', 'discovery', 'confirmation')


def sha(path):
    result = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            result.update(block)
    return result.hexdigest()


def absolute(value, label):
    path = Path(value).expanduser()
    if not path.is_absolute() or any(c in str(path) for c in '\n\r,') or 'REPLACE' in str(path):
        raise ValueError(label + ' must be a configured absolute path without Slurm delimiters')
    return path.resolve()


def save_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile('w', dir=path.parent, delete=False) as stream:
        json.dump(value, stream, indent=2, sort_keys=True)
        stream.write('\n')
        temporary = stream.name
    os.replace(temporary, path)


def write_environment(state):
    values = state['environment']
    content = '# Generated by scripts/cluster_setup.py; contains paths, never credentials.\n'
    content += ''.join('export ' + name + '=' + shlex.quote(str(value)) + '\n'
                       for name, value in sorted(values.items()))
    Path(state['env_file']).write_text(content)
    Path(state['env_file']).chmod(0o600)


def persist(state):
    save_json(Path(state['base_dir']) / 'setup-state.json', state)
    write_environment(state)


def configure(args):
    base = absolute(args.base_dir, '--base-dir')
    source = absolute(args.source_dir, '--source-dir')
    if base == source or source in base.parents:
        raise ValueError('--base-dir must be outside --source-dir and different from it')
    if not (source / 'scripts/slurm/freeze.py').is_file():
        raise ValueError('--source-dir must be this research checkout')
    if (base / 'setup-state.json').exists():
        raise ValueError('Setup already exists; reuse its --base-dir for later phases')
    python = shutil.which(args.python) if not Path(args.python).is_absolute() else args.python
    if not python or not Path(python).is_file():
        raise ValueError('Selected Python interpreter does not exist')
    env_file = absolute(args.env_file, '--env-file') if args.env_file else base / 'cluster.env'
    if source == env_file or source in env_file.parents:
        raise ValueError('--env-file must stay outside the source checkout')
    if env_file.exists():
        raise ValueError('Refusing to overwrite existing environment file')
    site = absolute(args.site_env, '--site-env') if args.site_env else None
    if site and (not site.is_file() or site.is_symlink()):
        raise ValueError('--site-env must be an existing reviewed regular shell script')
    base.mkdir(parents=True, exist_ok=True)
    env_file.parent.mkdir(parents=True, exist_ok=True)
    if site:
        shutil.copy2(site, base / 'site-environment.sh')
    env = {'REUSE_SSH_HOST': 'mliu171@ssh.ccv.brown.edu',
           'REUSE_SOURCE_DIR': str(source), 'REUSE_PROJECT_DIR': str(base / 'snapshot'),
           'REUSE_ENV_DIR': str(base / 'venv'), 'REUSE_RUN_ROOT': str(base / 'runs'),
           'REUSE_CACHE_ROOT': str(base / 'cache'), 'REUSE_LOOPVL_DIR': str(base / 'LoopVL'),
           'REUSE_MODEL_DIR': str(base / 'model'), 'REUSE_DATASET_DIR': str(base / 'datasets/scenes-v1'),
           'REUSE_SITE_ENV': str(base / 'snapshot/configs/site-environment.sh') if site else '',
           'REUSE_PARTITION': 'gpu-debug', 'REUSE_CPU_PARTITION': 'batch',
           'REUSE_ACCOUNT': 'default', 'REUSE_QOS': 'gpu-debug',
           'REUSE_CPU_ACCOUNT': 'default', 'REUSE_CPU_QOS': 'normal',
           'REUSE_GPU_FLAG': '--gres', 'REUSE_GPU_REQUEST': 'gpu:nvidia_rtx_a6000:1',
           'REUSE_CPUS': '8', 'REUSE_MEM': '32G', 'REUSE_TIME': '01:00:00',
           'REUSE_GPU_HOUR_CAP': '30', 'REUSE_CACHE_READY': '0',
           'REUSE_DTYPE': 'auto', 'REUSE_MIN_VRAM_GIB': '0'}
    state = {'schema_version': 1, 'base_dir': str(base), 'source_dir': str(source),
             'env_file': str(env_file), 'python': str(Path(python).resolve()),
             'site_env': str(base / 'site-environment.sh') if site else '',
             'environment': env, 'installed': False, 'staged': False, 'frozen': False}
    persist(state)
    print(json.dumps({'env_file': str(env_file), 'next': 'install', 'submitted_jobs': 0}, indent=2))
    return state


def load_state(base_dir):
    base = absolute(base_dir, '--base-dir')
    state = json.loads((base / 'setup-state.json').read_text())
    if state.get('base_dir') != str(base):
        raise ValueError('Preparation state was moved; configure a fresh base directory')
    for name in ('REUSE_PROJECT_DIR', 'REUSE_ENV_DIR', 'REUSE_RUN_ROOT', 'REUSE_CACHE_ROOT',
                 'REUSE_LOOPVL_DIR', 'REUSE_MODEL_DIR', 'REUSE_DATASET_DIR'):
        path = absolute(state['environment'][name], name)
        if base not in path.parents:
            raise ValueError('Preparation path escapes --base-dir: ' + name)
    return state


def run(state, command, capture=False, offline=False):
    """Pass argv unchanged even when module loading is needed; never interpolate it."""
    command = list(map(str, command))
    if state.get('site_env'):
        command = ['bash', '-lc', 'set -e; source "$1"; shift; exec "$@"',
                   'reuseinterp-site', state['site_env']] + command
    environment = dict(os.environ)
    environment.update(state['environment'])
    environment['PYTHONPATH'] = str(Path(state['source_dir']) / 'src')
    environment['HF_HOME'] = state['environment']['REUSE_CACHE_ROOT']
    if offline:
        environment.update(HF_HUB_OFFLINE='1', TRANSFORMERS_OFFLINE='1')
    print('+ ' + shlex.join(command), flush=True)
    result = subprocess.run(command, check=True, text=True, capture_output=capture, env=environment)
    return result.stdout if capture else ''


def env_python(state):
    return str(Path(state['environment']['REUSE_ENV_DIR']) / 'bin/python')


def check_platform(state):
    raw = run(state, [state['python'], '-c',
                     'import json,platform,sys; print(json.dumps({"system":platform.system(),"version":list(sys.version_info[:3])}))'], capture=True)
    info = json.loads(raw)
    if info['system'] != 'Linux' or tuple(info['version']) < (3, 12):
        raise ValueError('Official GPU environment requires Linux Python >=3.12; choose the site-supported interpreter')
    return info


def official_source(state):
    root = Path(state['environment']['REUSE_LOOPVL_DIR'])
    if not root.exists():
        run(state, ['git', 'clone', CODE_URL, root])
        run(state, ['git', '-C', root, 'checkout', '--detach', CODE_REVISION])
    revision = run(state, ['git', '-C', root, 'rev-parse', 'HEAD'], capture=True).strip()
    if revision != CODE_REVISION:
        raise ValueError('Existing LoopVL checkout differs from the pinned source revision')
    changes = run(state, ['git', '-C', root, 'status', '--porcelain', '--untracked-files=all'], capture=True)
    # Importing official preprocessing can generate harmless Python bytecode.
    changes = '\n'.join(line for line in changes.splitlines() if '__pycache__/' not in line)
    if changes.strip():
        raise ValueError('Existing LoopVL checkout has local changes; use a fresh base directory')
    return root


def install(args, state):
    if state['frozen']:
        raise ValueError('Frozen environment cannot be changed; configure a fresh base directory')
    state.update(installed=False, staged=False)
    state['environment']['REUSE_CACHE_READY'] = '0'
    persist(state)
    info = check_platform(state)
    if not args.use_installed_torch:
        if not args.torch_index_url:
            raise ValueError('Supply --torch-index-url approved by the site, or --use-installed-torch')
        parsed = urlsplit(args.torch_index_url)
        if parsed.scheme != 'https' or not parsed.netloc or parsed.username or parsed.password:
            raise ValueError('--torch-index-url must be an HTTPS package index without credentials')
    for version in (args.torch_version, args.torchvision_version):
        if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+(?:\+[A-Za-z0-9.]+)?', version):
            raise ValueError('Torch versions must be exact releases')
    venv = Path(state['environment']['REUSE_ENV_DIR'])
    if not (venv / 'bin/python').exists():
        command = [state['python'], '-m', 'venv']
        if args.use_installed_torch:
            command.append('--system-site-packages')
        run(state, command + [venv])
    upstream = official_source(state)
    python = env_python(state)
    # Keep later dependency resolution from replacing the selected CUDA build.
    constraints = Path(state['base_dir']) / 'torch-pair.constraints.txt'
    if not args.use_installed_torch:
        constraints.write_text('torch==' + args.torch_version + '\n'
                               'torchvision==' + args.torchvision_version + '\n')
        run(state, [python, '-m', 'pip', 'install', '--only-binary=:all:', '--index-url', args.torch_index_url,
                    'torch==' + args.torch_version, 'torchvision==' + args.torchvision_version])
    constraint_args = [] if args.use_installed_torch else ['--constraint', constraints]
    run(state, [python, '-m', 'pip', 'install', *constraint_args, '-r', upstream / 'runtime/requirements.txt'])
    run(state, [python, '-m', 'pip', 'install', *constraint_args, str(Path(state['source_dir'])) + '[plots]'])
    # This imports packages and runs a CPU operator only; no CUDA/model is initialized.
    pair = json.loads(run(state, [python, '-c',
        'import json,torch,torchvision; from torchvision.ops import nms; '
        'nms(torch.empty((0,4)),torch.empty((0,)),0.5); '
        'print(json.dumps({"torch":torch.__version__,"torchvision":torchvision.__version__,"cuda_runtime":torch.version.cuda}))'], capture=True))
    if not pair['cuda_runtime']:
        raise ValueError('CPU-only torch installation cannot run the scheduled GPU smoke; install the approved CUDA build')
    if not args.use_installed_torch:
        for name, requested in (('torch', args.torch_version), ('torchvision', args.torchvision_version)):
            actual = pair[name] if '+' in requested else pair[name].split('+')[0]
            if actual != requested:
                raise ValueError('Installed ' + name + ' differs from the requested CUDA pair')
    state.update(installed=True, python_platform=info, torch_pair=pair)
    persist(state)
    print(json.dumps({'installed': True, 'torch_pair': pair, 'next': 'stage'}, indent=2))


def pinned_configuration(source):
    configs = [json.loads((Path(source) / 'configs' / (name + '.yaml')).read_text()) for name in STAGES]
    reference = configs[0]
    required = ('code_revision', 'checkpoint_revision', 'checkpoint_hashes', 'dataset_hash')
    for config in configs:
        if any(config.get(key) != reference.get(key) for key in required):
            raise ValueError('All stage configurations must pin the same model/source/data bytes')
    if reference.get('code_revision') != CODE_REVISION or reference.get('checkpoint_revision') != CHECKPOINT_REVISION:
        raise ValueError('Configured source/checkpoint revision differs from the audited setup pins')
    hashes = reference.get('checkpoint_hashes', {})
    if not hashes or 'model.safetensors' not in hashes:
        raise ValueError('Configuration must include checkpoint byte hashes')
    for name, expected in hashes.items():
        relative = PurePosixPath(name)
        if relative.is_absolute() or '..' in relative.parts or not re.fullmatch(r'[a-f0-9]{64}', expected):
            raise ValueError('Unsafe checkpoint checksum entry')
    return reference


def extract_dataset(archive, checksum, destination):
    archive, checksum, destination = Path(archive), Path(checksum), Path(destination)
    cells = checksum.read_text().split()
    if len(cells) != 2 or cells[1].lstrip('*') != archive.name or sha(archive) != cells[0]:
        raise ValueError('Packaged dataset archive checksum mismatch')
    if destination.exists():
        return
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.data-stage-', dir=destination.parent) as temporary:
        with tarfile.open(archive, 'r:gz') as bundle:
            members = bundle.getmembers()
            if not members:
                raise ValueError('Empty dataset archive')
            seen = set()
            for member in members:
                name = PurePosixPath(member.name)
                if (name.is_absolute() or '..' in name.parts or not name.parts or name.parts[0] != 'scenes-v1'
                        or not (member.isfile() or member.isdir()) or str(name) in seen):
                    raise ValueError('Unsafe dataset archive member: ' + member.name)
                seen.add(str(name))
            # Validated regular files/directories only; compatible with Python 3.9.
            for member in members:
                target = Path(temporary).joinpath(*PurePosixPath(member.name).parts)
                if member.isdir():
                    target.mkdir(parents=True, exist_ok=True)
                else:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    with bundle.extractfile(member) as incoming, target.open('wb') as outgoing:
                        shutil.copyfileobj(incoming, outgoing)
        extracted = Path(temporary) / 'scenes-v1'
        if not (extracted / 'manifest.json').is_file():
            raise ValueError('Dataset archive is missing manifest.json')
        os.replace(extracted, destination)


def verify_checkpoint(root, config):
    root = Path(root)
    for name, expected in config['checkpoint_hashes'].items():
        path = root / name
        if not path.is_file() or sha(path) != expected:
            raise ValueError('Pinned checkpoint checksum mismatch: ' + name)
    return dict(config['checkpoint_hashes'])


def verify_staged(state):
    config = pinned_configuration(state['source_dir'])
    official_source(state)
    hashes = verify_checkpoint(state['environment']['REUSE_MODEL_DIR'], config)
    raw = run(state, [env_python(state), '-c',
        'import json,sys; from reuseinterp.data import validate_dataset; '
        'print(json.dumps(validate_dataset(sys.argv[1])))', state['environment']['REUSE_DATASET_DIR']], capture=True, offline=True)
    data_report = json.loads(raw)
    if data_report.get('dataset_hash') != config['dataset_hash']:
        raise ValueError('Staged dataset hash differs from the pinned study dataset')
    # Official loader opens only metadata, tokenizer and image processor here.
    # Calling LoopVLForConditionalGeneration.from_pretrained remains GPU-only.
    raw = run(state, [env_python(state), '-c',
        'import json,sys; sys.path.insert(0,sys.argv[1]); '
        'from modeling_loopvl import load_tokenizer_and_processor; '
        'tokenizer,processor=load_tokenizer_and_processor(sys.argv[2]); '
        'print(json.dumps({"tokenizer":type(tokenizer).__name__,"processor":type(processor).__name__,"weights_loaded":False}))',
        str(Path(state['environment']['REUSE_LOOPVL_DIR']) / 'runtime'), state['environment']['REUSE_MODEL_DIR']], capture=True, offline=True)
    return {'checkpoint_hashes': hashes, 'dataset': data_report, 'offline_components': json.loads(raw)}


def stage(args, state):
    if not state['installed']:
        raise ValueError('Complete install first')
    if state['frozen']:
        raise ValueError('Frozen environment cannot be restaged; use a fresh base directory')
    # Clear readiness before every attempted restaging, including failed retries.
    state['staged'] = False
    state['environment']['REUSE_CACHE_READY'] = '0'
    persist(state)
    pinned_configuration(state['source_dir'])
    archive = Path(state['source_dir']) / 'assets/scenes-v1.tar.gz'
    extract_dataset(archive, Path(str(archive) + '.sha256'), state['environment']['REUSE_DATASET_DIR'])
    run(state, [env_python(state), '-c',
        'import sys; from huggingface_hub import snapshot_download; '
        'snapshot_download(repo_id=sys.argv[1],revision=sys.argv[2],local_dir=sys.argv[3])',
        MODEL_REPO, CHECKPOINT_REVISION, state['environment']['REUSE_MODEL_DIR']])
    evidence = verify_staged(state)
    save_json(Path(state['base_dir']) / 'staging-evidence.json', evidence)
    state['staged'] = True
    state['environment']['REUSE_CACHE_READY'] = '1'
    persist(state)
    print(json.dumps({'staged': True, 'evidence': str(Path(state['base_dir']) / 'staging-evidence.json'), 'next': 'freeze'}, indent=2))


def freeze_module(source):
    spec = importlib.util.spec_from_file_location('cluster_freeze', Path(source) / 'scripts/slurm/freeze.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def freeze(args, state):
    if not state['installed'] or not state['staged']:
        raise ValueError('Complete installation and verified staging first')
    if state['frozen']:
        raise ValueError('Snapshot already frozen; do not overwrite it')
    evidence = verify_staged(state)
    base, source = Path(state['base_dir']), Path(state['source_dir'])
    module = freeze_module(source)
    lock = base / 'cluster-dependencies.lock'
    lock_text = run(state, [env_python(state), '-m', 'pip', 'freeze', '--all'], capture=True)
    # Protect snapshot manifests and logs from credential-bearing package URLs.
    if re.search(r'https?://[^\s/]*@', lock_text):
        raise ValueError('Dependency lock contains a credential-bearing URL; use an approved credential-free package source')
    lock.write_text(lock_text)
    commit = run(state, ['git', '-C', source, 'rev-parse', 'HEAD'], capture=True).strip()
    dirty = run(state, ['git', '-C', source, 'status', '--porcelain', '--untracked-files=all'], capture=True)
    diff = run(state, ['git', '-C', source, 'diff', '--binary', 'HEAD'], capture=True)
    preparation = base / 'preparation'
    if preparation.exists():
        raise ValueError('Preparation copy already exists after an interrupted freeze; inspect it and use a fresh base directory')
    preparation.mkdir()
    original_hashes = {}
    for path in module.files(source):
        if 'local' in path.name and path.suffix in {'.env', '.sh'}:
            continue
        relative = path.relative_to(source)
        target = preparation / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        original_hashes[str(relative)] = sha(path)
    for path in (preparation / 'configs').glob('*.yaml'):
        config = json.loads(path.read_text())
        if 'dataset_dir' in config:
            config['dataset_dir'] = state['environment']['REUSE_DATASET_DIR']
            path.write_text(json.dumps(config, indent=2) + '\n')
    if state['site_env']:
        shutil.copy2(state['site_env'], preparation / 'configs/site-environment.sh')
    provenance = {'source_commit': commit, 'source_worktree_status': dirty,
                  'source_diff_sha256': hashlib.sha256(diff.encode()).hexdigest(),
                  'source_files': original_hashes,
                  'transformations': ['dataset_dir in JSON YAML configs set to approved absolute shared path',
                                      'reviewed optional site-environment.sh copied into snapshot'],
                  'staging_evidence_sha256': sha(base / 'staging-evidence.json')}
    save_json(preparation / 'source_provenance.json', provenance)
    snapshot = Path(state['environment']['REUSE_PROJECT_DIR'])
    run(state, [env_python(state), source / 'scripts/slurm/freeze.py', '--source', preparation,
                '--destination', snapshot, '--dependency-lock', lock])
    manifest_path = snapshot / 'snapshot_manifest.json'
    manifest = json.loads(manifest_path.read_text())
    manifest['source_commit'] = commit
    save_json(manifest_path, manifest)
    snapshot_hash = module.verify(snapshot)
    state.update(frozen=True, snapshot_sha256=snapshot_hash)
    persist(state)
    print(json.dumps({'frozen': True, 'snapshot_sha256': snapshot_hash,
                      'env_file': state['env_file'], 'next': 'scheduled singleton validate smoke'}, indent=2))


def status(args, state):
    report = {key: state.get(key) for key in ('installed', 'staged', 'frozen', 'snapshot_sha256', 'torch_pair', 'env_file')}
    report['cache_ready'] = state['environment']['REUSE_CACHE_READY']
    report['gpu_checks'] = 'pending; setup never submits a job or loads model weights'
    if state['frozen']:
        report['snapshot_sha256'] = freeze_module(state['source_dir']).verify(state['environment']['REUSE_PROJECT_DIR'])
    print(json.dumps(report, indent=2))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='phase', required=True)
    setup = commands.add_parser('configure', help='Create external settings and preparation state')
    setup.add_argument('--base-dir', required=True)
    setup.add_argument('--source-dir', required=True)
    setup.add_argument('--python', default='python3')
    setup.add_argument('--env-file')
    setup.add_argument('--site-env', help='Absolute reviewed shell script with site-supported module loads')
    for name in ('install', 'stage', 'freeze', 'status'):
        command = commands.add_parser(name)
        command.add_argument('--base-dir', required=True)
        if name == 'install':
            command.add_argument('--torch-index-url', help='Explicit site-approved HTTPS PyTorch wheel index')
            command.add_argument('--torch-version', default='2.8.0+cu128')
            command.add_argument('--torchvision-version', default='0.23.0+cu128')
            command.add_argument('--use-installed-torch', action='store_true', help='Use a compatible CUDA pair supplied by site modules')
    args = parser.parse_args(argv)
    if args.phase == 'configure':
        configure(args)
    else:
        state = load_state(args.base_dir)
        globals()[args.phase](args, state)
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, OSError, KeyError, subprocess.CalledProcessError, tarfile.TarError) as exc:
        print('cluster_setup: ' + str(exc), file=sys.stderr)
        sys.exit(2)
