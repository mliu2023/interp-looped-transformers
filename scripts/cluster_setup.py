def sha(path):
    result = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            result.update(block)
    return result.hexdigest()


def absolute(value, label):
    path = Path(value).expanduser()
    if not path.is_absolute() or any(c in str(path) for c in '\n\r,') or 'REPLACE' in str(path):
        raise ValueError(label + ' must be a configured absolute path without Slurm delimiters')
    return path.resolve()


def save_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile('w', dir=path.parent, delete=False) as stream:
        json.dump(value, stream, indent=2, sort_keys=True)
        stream.write('\n')
        temporary = stream.name
    os.replace(temporary, path)


def write_environment(state):
    values = state['environment']
    content = '# Generated by scripts/cluster_setup.py; contains paths, never credentials.\n'
    content += ''.join('export ' + name + '=' + shlex.quote(str(value)) + '\n'
                       for name, value in sorted(values.items()))
    Path(state['env_file']).write_text(content)
    Path(state['env_file']).chmod(0o600)


def profile_suffix(profile):
    if profile is None:
        return ''
    if not re.fullmatch(r'[a-z][a-z0-9-]{0,31}', profile):
        raise ValueError('Profile must be a short lowercase name containing letters, digits, and hyphens')
    return '-' + profile


def artifact_path(state, stem, extension):
    return Path(state['base_dir']) / (stem + profile_suffix(state.get('profile')) + extension)


def persist(state):
    save_json(artifact_path(state, 'setup-state', '.json'), state)
    write_environment(state)


